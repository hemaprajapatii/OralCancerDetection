import React from 'react';
import { ShieldAlert, ShieldCheck, HelpCircle, RotateCcw } from 'lucide-react';

export default function ResultDisplay({ result, onReset }) {
  if (!result) {
    return (
      <div className="card-panel">
        <h2 className="card-title">Analysis Results</h2>
        <p className="card-subtitle">Model prediction and score breakdown will appear here after analysis.</p>

        <div className="result-placeholder">
          <HelpCircle className="placeholder-icon" />
          <p style={{ fontWeight: 500, marginBottom: '4px' }}>No Analysis Performed Yet</p>
          <p style={{ fontSize: '0.8rem' }}>Select an oral image on the left and click &ldquo;Analyze Image&rdquo;.</p>
        </div>
      </div>
    );
  }

  const isCancer = result.prediction === 'CANCER';
  const cancerPct = (result.cancer_score * 100).toFixed(1);
  const nonCancerPct = (result.non_cancer_score * 100).toFixed(1);

  return (
    <div className="card-panel">
      <h2 className="card-title">Analysis Results</h2>
      <p className="card-subtitle">
        Predictions generated by MobileNetV2.
      </p>

      <div className="result-card-inner">
        {/* Prediction Headline Banner */}
        <div className={`prediction-banner ${isCancer ? 'cancer' : 'non-cancer'}`} role="status">
          <div className="prediction-icon-circle">
            {isCancer ? <ShieldAlert size={28} /> : <ShieldCheck size={28} />}
          </div>
          <div>
            <div className="prediction-label">Predicted Class (Model Classification)</div>
            <div className="prediction-headline">{result.prediction}</div>
            <div className="prediction-class-idx">
              Index: {result.class_index} &bull; Decision Threshold: {result.threshold}
            </div>
          </div>
        </div>

        {/* Model-Derived Score Breakdown */}
        <div className="scores-section">
          {/* Cancer Score Row */}
          <div className="score-row">
            <div className="score-header">
              <span className="score-title">CANCER Model Score (Class 0):</span>
              <span className="score-percent" style={{ color: 'var(--cancer-color)' }}>
                {cancerPct}%
              </span>
            </div>
            <div className="progress-track" aria-hidden="true">
              <div
                className="progress-fill fill-cancer"
                style={{ width: `${Math.min(100, Math.max(0, Number(cancerPct)))}%` }}
              ></div>
            </div>
          </div>

          {/* Non-Cancer Score Row */}
          <div className="score-row">
            <div className="score-header">
              <span className="score-title">NON CANCER Model Score (Class 1):</span>
              <span className="score-percent" style={{ color: 'var(--noncancer-color)' }}>
                {nonCancerPct}%
              </span>
            </div>
            <div className="progress-track" aria-hidden="true">
              <div
                className="progress-fill fill-noncancer"
                style={{ width: `${Math.min(100, Math.max(0, Number(nonCancerPct)))}%` }}
              ></div>
            </div>
          </div>
          <p style={{ fontSize: '0.74rem', color: 'var(--text-muted)' }}>
            *Scores are direct uncalibrated mathematical outputs from the neural network and do not represent clinically validated diagnostic probabilities.
          </p>
        </div>

        {/* Research Transparency Panel */}
        <div className="transparency-panel">
          <div className="transparency-title">
            Research Transparency Details
          </div>
          <div className="transparency-grid">
            <div className="transparency-item">
              <div className="t-label">Raw Sigmoid Output (s)</div>
              <div className="t-val">{result.raw_sigmoid_score}</div>
            </div>
            <div className="transparency-item">
              <div className="t-label">Operating Threshold</div>
              <div className="t-val">{result.threshold}</div>
            </div>
          </div>
          <div className="transparency-note">
            <strong>Sigmoid Mapping Logic:</strong> In this training setup, Class 1 is NON CANCER. The raw sigmoid value <em>s</em> directly represents the NON CANCER score. The complementary score (1 &minus; <em>s</em>) represents the CANCER score. Whenever <em>s</em> &le; {result.threshold}, CANCER is predicted.
          </div>
        </div>

        {/* Reset Action */}
        <button
          type="button"
          className="btn-secondary"
          onClick={onReset}
          style={{ width: '100%', marginTop: '6px' }}
        >
          <RotateCcw size={16} />
          <span>Analyze Another Image</span>
        </button>
      </div>
    </div>
  );
}
